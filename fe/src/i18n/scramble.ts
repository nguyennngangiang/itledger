// The shuffled catalog: one language per key, chosen by hand.
//
// Pressing the globe in the header swaps every string here for its entry; pressing
// again returns to the English in `catalog.ts`. Each key keeps the SAME language
// every time rather than drawing fresh on each press — that way one string is one
// translation to write (~460) instead of twelve (~5,500), and a word doesn't
// flicker between languages when you toggle twice.
//
// Languages are spread deliberately, not randomly: every screen shows at least one
// CJK, one right-to-left, one Latin and one joke language, so a glance tells you
// the shuffle is on — and the Arabic entries are placed where they will actually
// exercise the `dir="auto"` handling (table headers, buttons, inline prose).
//
// A key with no entry here falls back to English, so this file can be filled in
// gradually. `scripts/check-i18n.mjs` reports how many are still missing.
//
// The Vietnamese entries are mostly the app's ORIGINAL copy, written by the team
// before everything was standardised on English — recovered from git rather than
// re-translated, so they read the way the people who use this actually write.

